import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const translations = {};
for (const locale of ['zh-Hant', 'zh-Hans']) {
  translations[locale] = JSON.parse(await readFile(new URL(`locales/${locale}.json`, root), 'utf8'));
}
const traditional = translations['zh-Hant'];
const simplified = translations['zh-Hans'];
for (const key of Object.keys(traditional.strings)) {
  if (!simplified.strings[key]) throw new Error(`Missing Simplified Chinese translation: ${key}`);
}
for (const [key, entry] of Object.entries(traditional.cases)) {
  for (const field of ['category', 'title', 'description', 'input', 'work', 'result', 'agent', 'review']) {
    if (!entry[field] || !simplified.cases[key]?.[field]) throw new Error(`Missing case translation: ${key}.${field}`);
  }
}
for (const locale of Object.values(translations)) {
  if (locale.demoMessages.length !== 3) throw new Error('All three demo messages must be translated.');
}
await writeFile(new URL('translations.js', root),
  `// Generated by scripts/build-translations.mjs. Edit locales/*.json.\nconst SITE_TRANSLATIONS = ${JSON.stringify(translations, null, 2)};\n`);
console.log('Built Traditional and Simplified Chinese translations.');
